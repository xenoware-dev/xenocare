import { ArrowLeft, HeartPulse, Printer, ShieldCheck } from 'lucide-react';
import type { ReactNode } from 'react';
import { useNavigate } from 'react-router';
import { Button } from '@/components/ui/button';

export interface DocMeta {
  label: string;
  value: ReactNode;
}

/**
 * Medical-report layout for finished clinical records: letterhead, patient block,
 * body, and an electronic-signature footer. Prints cleanly on A4 (Print → Save as PDF).
 */
export function ClinicalDocument({
  title,
  branch,
  docNo,
  patient,
  meta,
  signedBy,
  signedAt,
  statusNote,
  actions,
  children,
}: {
  title: string;
  branch?: { name: string; address?: string | null; phone?: string | null } | null;
  docNo?: string;
  patient: DocMeta[];
  meta: DocMeta[];
  signedBy?: string | null;
  signedAt?: string | null;
  statusNote?: string;
  actions?: ReactNode;
  children: ReactNode;
}) {
  const navigate = useNavigate();
  const fmt = (d: string) => new Intl.DateTimeFormat('en-IN', { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(d));

  return (
    <div className="mx-auto max-w-4xl space-y-4 print:max-w-none print:space-y-0">
      <div className="flex flex-wrap items-center justify-between gap-2 print:hidden">
        <Button variant="ghost" size="sm" className="-ml-2" onClick={() => navigate(-1)}>
          <ArrowLeft /> Back
        </Button>
        <div className="flex flex-wrap gap-2">
          {actions}
          <Button variant="outline" size="sm" onClick={() => window.print()}>
            <Printer /> Print / PDF
          </Button>
        </div>
      </div>

      <article className="rounded-xl border bg-card shadow-sm print:rounded-none print:border-0 print:shadow-none">
        {/* Letterhead */}
        <header className="flex flex-wrap items-start justify-between gap-4 border-b-2 border-primary px-6 py-5 sm:px-8 print:px-0">
          <div className="flex items-center gap-3">
            <span className="flex size-11 items-center justify-center rounded-xl bg-primary text-primary-foreground print:border print:bg-transparent print:text-black">
              <HeartPulse className="size-6" aria-hidden />
            </span>
            <div>
              <p className="text-lg leading-tight font-bold">XenoCare Therapy Centre</p>
              <p className="text-sm text-muted-foreground">
                {branch?.name ?? ''}
                {branch?.address && ` · ${branch.address}`}
                {branch?.phone && ` · ${branch.phone}`}
              </p>
            </div>
          </div>
          <div className="text-right">
            <p className="text-base font-bold tracking-wide uppercase">{title}</p>
            {docNo && <p className="font-mono text-xs text-muted-foreground">Ref: {docNo}</p>}
          </div>
        </header>

        {/* Patient + record details */}
        <section className="grid gap-x-8 gap-y-1.5 border-b bg-muted/30 px-6 py-4 text-sm sm:grid-cols-2 sm:px-8 print:bg-transparent print:px-0">
          {[...patient, ...meta].map((m) => (
            <div key={m.label} className="flex gap-3">
              <span className="w-28 shrink-0 text-muted-foreground">{m.label}</span>
              <span className="font-medium">{m.value || '—'}</span>
            </div>
          ))}
        </section>

        {/* Body */}
        <div className="space-y-6 px-6 py-6 sm:px-8 print:px-0">{children}</div>

        {/* Signature */}
        <footer className="flex flex-wrap items-end justify-between gap-4 border-t px-6 py-5 text-sm sm:px-8 print:px-0">
          {signedBy && signedAt ? (
            <div className="flex items-center gap-2">
              <ShieldCheck className="size-5 text-success print:text-black" aria-hidden />
              <div>
                <p className="font-semibold">Electronically signed by {signedBy}</p>
                <p className="text-xs text-muted-foreground">{fmt(signedAt)} · record locked</p>
              </div>
            </div>
          ) : (
            <p className="text-muted-foreground">{statusNote ?? 'Not signed'}</p>
          )}
          <p className="text-xs text-muted-foreground">Confidential clinical record · generated by XenoCare</p>
        </footer>
      </article>
    </div>
  );
}

export function ageFrom(dob: string | null | undefined) {
  if (!dob) return null;
  const d = new Date(dob);
  const now = new Date();
  let y = now.getFullYear() - d.getFullYear();
  if (now < new Date(now.getFullYear(), d.getMonth(), d.getDate())) y--;
  return y;
}
